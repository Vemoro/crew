import type { Pool } from 'pg';
import { writeTransaction } from './db';

const schema = `
CREATE TABLE people (
  id integer PRIMARY KEY,
  auth_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  email text NOT NULL UNIQUE, name text NOT NULL,
  role text NOT NULL CHECK (role IN ('staff','admin')),
  status text NOT NULL CHECK (status IN ('pending','active','rejected')),
  availability text NOT NULL DEFAULT '', review_note text NOT NULL DEFAULT '',
  access_suspended smallint NOT NULL DEFAULT 0 CHECK (access_suspended IN (0,1)),
  access_revision integer NOT NULL DEFAULT 1,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE qualifications (
  id integer PRIMARY KEY, person integer NOT NULL REFERENCES people(id),
  name text NOT NULL, valid_until text NOT NULL DEFAULT '',
  verified smallint NOT NULL DEFAULT 0 CHECK (verified IN (0,1)),
  evidence bytea, revision integer NOT NULL DEFAULT 1, UNIQUE (person,name)
);
CREATE TABLE qualification_requests (
  person integer NOT NULL REFERENCES people(id) ON DELETE CASCADE,
  name text NOT NULL, note text NOT NULL,
  state text NOT NULL CHECK (state IN ('open','submitted','done')),
  PRIMARY KEY (person,name)
);
CREATE TABLE events (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, title text NOT NULL, location text NOT NULL,
  reference text NOT NULL DEFAULT '', instructions text NOT NULL DEFAULT '', revision integer NOT NULL DEFAULT 1
);
CREATE TABLE shifts (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, event integer NOT NULL REFERENCES events(id),
  title text NOT NULL, starts text NOT NULL, ends text NOT NULL,
  slots integer NOT NULL CHECK (slots > 0), cents integer NOT NULL CHECK (cents >= 0),
  requirements text NOT NULL, questions text NOT NULL,
  visibility text NOT NULL CHECK (visibility IN ('draft','pool','invite')),
  cancelled_at text, locked_location text, locked_instructions text,
  placement_revision integer NOT NULL DEFAULT 1,
  anonymous_assigned integer NOT NULL DEFAULT 0 CHECK (anonymous_assigned >= 0),
  CHECK (starts < ends)
);
CREATE TABLE invitations (
  shift integer NOT NULL REFERENCES shifts(id), person integer NOT NULL REFERENCES people(id),
  PRIMARY KEY (shift,person)
);
CREATE TABLE responses (
  shift integer NOT NULL REFERENCES shifts(id), person integer NOT NULL REFERENCES people(id),
  status text NOT NULL CHECK (status IN ('interested','assigned','withdrawn')),
  answers text NOT NULL, revision integer NOT NULL DEFAULT 1,
  released_by_dispo smallint NOT NULL DEFAULT 0 CHECK (released_by_dispo IN (0,1)),
  PRIMARY KEY (shift,person)
);
CREATE INDEX responses_person_status ON responses(person,status);
CREATE INDEX invitations_person ON invitations(person);
CREATE TABLE erased_ids (kind text PRIMARY KEY, greatest integer NOT NULL);
INSERT INTO erased_ids VALUES ('people',0),('qualifications',0);
CREATE TABLE sqlite_import (imported_at timestamptz PRIMARY KEY DEFAULT now());

CREATE VIEW auth_users AS
  SELECT auth_id AS id,email,name,false AS "emailVerified",NULL::text AS image,"createdAt","updatedAt" FROM people;
CREATE TABLE auth_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), "userId" uuid NOT NULL REFERENCES people(auth_id) ON DELETE CASCADE,
  token text NOT NULL UNIQUE, "expiresAt" timestamptz NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(), "updatedAt" timestamptz NOT NULL DEFAULT now(),
  "ipAddress" text, "userAgent" text
);
CREATE INDEX auth_sessions_user ON auth_sessions("userId");
CREATE TABLE auth_accounts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), "userId" uuid NOT NULL REFERENCES people(auth_id) ON DELETE CASCADE,
  "providerId" text NOT NULL, "accountId" text NOT NULL, password text,
  "accessToken" text, "refreshToken" text, "idToken" text,
  "accessTokenExpiresAt" timestamptz, "refreshTokenExpiresAt" timestamptz, scope text,
  "createdAt" timestamptz NOT NULL DEFAULT now(), "updatedAt" timestamptz NOT NULL DEFAULT now(),
  UNIQUE ("providerId","accountId")
);
CREATE INDEX auth_accounts_user ON auth_accounts("userId");
CREATE TABLE auth_verifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), identifier text NOT NULL, value text NOT NULL,
  "expiresAt" timestamptz NOT NULL, "createdAt" timestamptz NOT NULL DEFAULT now(), "updatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX auth_verifications_identifier ON auth_verifications(identifier);
`;

export async function migrate(pool: Pool) {
  await writeTransaction(pool, async db => {
    await db.query('CREATE TABLE IF NOT EXISTS crew_schema (version integer PRIMARY KEY)');
    const result = await db.query<{ version: number }>('SELECT version FROM crew_schema');
    if (result.rows.some(row => row.version !== 1)) throw new Error('Unbekannte Version des Crew-Datenbankschemas.');
    if (result.rowCount === 0) {
      await db.query(schema);
      await db.query('INSERT INTO crew_schema VALUES (1)');
    }
  });
}
